"""Turn a validated (or provisional) profile into the C++ header the ESP32 firmware compiles in.

  python tools/export_edge_profile.py data/real/profiles/<profile>.json \
      --output device/firmware/vfm_edge/profile.h [--allow-unvalidated]

The profile is verified first (checksum, schema, monotonic, held-out validation). The header
holds the same coefficients and valid ranges the gateway uses, so the ESP32 and the laptop
compute the same estimate from the same profile.
"""

import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from gateway.estimator import ProfileError, load_profile  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "device" / "firmware" / "vfm_edge" / "profile.h"
MAX_WEAK = 4


def _f(value):
    text = f"{float(value):.9g}"
    if not any(ch in text for ch in ".en"):
        text += ".0"                       # C++ needs 5.0f, not 5f
    return text + "f"


def header_text(profile, source_name="profile.json"):
    if len(profile["weak_regions_l_min"]) > MAX_WEAK:
        raise ProfileError(f"more than {MAX_WEAK} weak flow ranges; the firmware cannot hold them")
    c0, c1, c2 = profile["model"]["coefficients"]
    dom = profile["domain"]
    temp = dom.get("temp_c") or [-1000.0, 1000.0]
    weak = profile["weak_regions_l_min"]
    weak_lo = [w[0] for w in weak] + [0.0] * (MAX_WEAK - len(weak))
    weak_hi = [w[1] for w in weak] + [0.0] * (MAX_WEAK - len(weak))
    method = profile["evaluation"]["method"]
    label = "PROVISIONAL, NOT VERIFIED" if profile.get("provisional") else (
        "validated on held-out runs" if method == "held_out_validation" else "NOT validated")
    return f"""// GENERATED by tools/export_edge_profile.py from {source_name}. Do not edit by hand.
// Model {profile['checksum_sha256'][:12]}, created {profile.get('created_utc')}: {label}.
#pragma once
#include "vfm_estimator.h"

static const EdgeProfile EDGE_PROFILE = {{
  {_f(c0)}, {_f(c1)}, {_f(c2)},
  {_f(dom['flow_l_min'][0])}, {_f(dom['flow_l_min'][1])},
  {_f(dom['power_w'][0])}, {_f(dom['power_w'][1])},
  {_f(dom['volts'][0])}, {_f(dom['volts'][1])},
  {_f(temp[0])}, {_f(temp[1])},
  {_f(profile['power_noise_w'])},
  {len(weak)},
  {{{', '.join(_f(v) for v in weak_lo)}}},
  {{{', '.join(_f(v) for v in weak_hi)}}},
  "{profile['checksum_sha256'][:12]}"
}};
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("profile")
    parser.add_argument("--output", default=str(DEFAULT_OUTPUT))
    parser.add_argument("--allow-unvalidated", action="store_true")
    args = parser.parse_args()
    try:
        profile = load_profile(args.profile, allow_unvalidated=args.allow_unvalidated)
        text = header_text(profile, Path(args.profile).name)
    except ProfileError as problem:
        parser.error(str(problem))
    Path(args.output).write_text(text, encoding="utf-8")
    print(f"Wrote {args.output} for model {profile['checksum_sha256'][:12]}")


if __name__ == "__main__":
    main()
